"""Turn a numbered joke list into SQL inserts for the rating app.

Usage:
    python scripts/make_seed_sql.py jokes/by_people.txt --source curated > db/seed.sql

Input: one joke per line, optionally prefixed with "N. ". Blank lines are ignored.
Jokes already in the database (same text, case-insensitive) are skipped, so the
output is safe to run more than once.
"""

import argparse
import re
import sys

NUMBER_PREFIX = re.compile(r"^\s*\d+[.)]\s*")


def sql_str(value):
    if value is None:
        return "null"
    return "'" + value.replace("'", "''") + "'"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("path", help="text file, one joke per line")
    parser.add_argument("--source", default="curated", choices=["curated", "submitted", "model"])
    parser.add_argument("--model", help="model name (for --source model)")
    parser.add_argument("--prompt-version", help="prompt version (for --source model)")
    parser.add_argument("--language", default="en")
    args = parser.parse_args()

    with open(args.path, encoding="utf-8") as f:
        jokes = [NUMBER_PREFIX.sub("", line).strip() for line in f]
    jokes = [j for j in jokes if j]

    out = sys.stdout
    out.write(f"-- Generated by scripts/make_seed_sql.py from {args.path}\n")
    for joke in jokes:
        out.write(
            "insert into jokes (text, source, model, prompt_version, language)\n"
            f"select {sql_str(joke)}, {sql_str(args.source)}, {sql_str(args.model)}, "
            f"{sql_str(args.prompt_version)}, {sql_str(args.language)}\n"
            f"where not exists (select 1 from jokes where lower(text) = lower({sql_str(joke)}));\n"
        )


if __name__ == "__main__":
    main()
